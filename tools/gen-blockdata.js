#!/usr/bin/env node
// Writes brain/schematic/blockdata.js: every vanilla 1.21.6 block with the properties a schematic keeps and their allowed values, plus the default state.
// The schematic agent (brain/schematic/agent.js) validates what a model places against it. Run again only for a new Minecraft version:
//   node tools/gen-blockdata.js [version]
'use strict'
const fs = require('fs')
const path = require('path')
const version = process.argv[2] || '1.21.6'
const md = require('minecraft-data')(version)
const KEEP = ['facing', 'half', 'type', 'open', 'level', 'hinge', 'axis', 'face', 'attached', 'shape']
const out = {}
for (const b of md.blocksArray) {
  const props = {}, def = {}
  const states = b.states || []
  let rest = b.defaultState - b.minStateId
  // block states are numbered with the LAST property varying fastest
  const vals = states.map(s => s.num_values || (s.values ? s.values.length : 2))
  const pick = new Array(states.length)
  for (let i = states.length - 1; i >= 0; i--) { pick[i] = rest % vals[i]; rest = Math.floor(rest / vals[i]) }
  states.forEach((s, i) => {
    if (!KEEP.includes(s.name)) return
    const values = s.type === 'bool' ? ['true', 'false'] : s.type === 'int' ? Array.from({ length: s.num_values }, (_, k) => String(k)) : s.values
    props[s.name] = values
    // md lists bool values as [true, false] in that order, so index 0 is "true"
    def[s.name] = String(values[pick[i]])
  })
  out[b.name] = Object.keys(props).length ? { p: props, d: def } : 0
}
const text = `// brain/schematic/blockdata.js: GENERATED by tools/gen-blockdata.js from minecraft-data ${version}. Do not edit.\n// block name -> 0 (no property a schematic keeps) or { p: { property: [allowed values] }, d: { property: default value } }\n'use strict'\nmodule.exports = { version: ${JSON.stringify(version)}, blocks: ${JSON.stringify(out)} }\n`
fs.writeFileSync(path.join(__dirname, '..', 'brain', 'schematic', 'blockdata.js'), text)
console.log(`${Object.keys(out).length} blocks, ${(text.length / 1024).toFixed(0)} KB`)
